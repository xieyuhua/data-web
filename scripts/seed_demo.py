class Api:
    def __init__(self, base: str, token: str = ""):
        self.base = base.rstrip("/")
        self.token = token

    def call(self, method: str, path: str, body=None, expect=(200,)):
        data = json.dumps(body).encode("utf-8") if body is not None else None
        req = urllib.request.Request(
            self.base + "/api" + path, method=method, data=data,
            headers={"Content-Type": "application/json",
                     **({"Authorization": "Bearer " + self.token} if self.token else {})},
        )
        try:
            with urllib.request.urlopen(req, timeout=120) as resp:
                raw = resp.read()
                return json.loads(raw) if raw else {}
        except urllib.error.HTTPError as e:
            raw = e.read()
            try:
                payload = json.loads(raw)
            except Exception:
                payload = {"message": raw.decode("utf-8", "replace")[:300]}
            if e.code in expect:
                return payload
            raise RuntimeError(f"{method} {path} -> {e.code}: {payload.get('message')}") from None


def login(api: Api, user: str, password: str) -> Api:
    res = api.call("POST", "/auth/login", {"username": user, "password": password})
    return Api(api.base, res["data"]["token"])


def find(items, name, key="name"):
    for it in items:
        if it.get(key) == name:
            return it
    return None


