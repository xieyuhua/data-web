def ensure_datasets(api: Api, ds_id: int) -> dict:
    items = api.call("GET", "/datasets")["data"]
    out = {}
    for spec in DATASETS:
        existing = find(items, spec["name"])
        payload = {**spec, "dataSourceId": ds_id, "defaultLimit": 1000}
        if existing:
            api.call("PUT", f"/datasets/{existing['id']}", payload)
            out[spec["name"]] = existing["id"]
            print(f"  dataset reused #{existing['id']} {spec['name']}")
        else:
            ds = api.call("POST", "/datasets", payload)["data"]
            out[spec["name"]] = ds["id"]
            print(f"  dataset created #{ds['id']} {spec['name']}")
    return out


